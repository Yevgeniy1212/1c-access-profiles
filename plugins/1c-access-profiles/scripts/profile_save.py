#!/usr/bin/env python3
"""Создание или обновление профиля групп доступа в базе.

Два режима:
  --dry-run (по умолчанию)  показать, что будет сделано, не записывая в базу
  --apply                   записать в базу

    python scripts/profile_save.py --name "Склад (копия)" --from "Склад"
    python scripts/profile_save.py --name "Склад (копия)" --from "Склад" --apply

Для записи в 1С должен быть включён флажок «Записать» в форме MCP Toolkit
(блок «Автоматически разрешать операции»), иначе платформа запросит подтверждение
в окне 1С.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from mcp_client import (  # noqa: E402
    Client,
    add_common_args,
    bsl_string,
    fail,
    resolve_url,
    setup_stdout,
)

EXISTS = """
Запрос = Новый Запрос;
Запрос.Текст = "ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка КАК Ссылка ИЗ Справочник.ПрофилиГруппДоступа КАК П ГДЕ П.Наименование = &Имя И НЕ П.ПометкаУдаления";
Запрос.УстановитьПараметр("Имя", {name});
Выб = Запрос.Выполнить().Выбрать();
Рез = "нет";
Если Выб.Следующий() Тогда
	Профиль = Выб.Ссылка;
	Рез = "да|" + Строка(Профиль.Роли.Количество());
КонецЕсли;
Результат = Рез;
"""

ROLES_OF = """
Запрос = Новый Запрос;
Запрос.Текст = "ВЫБРАТЬ П.Ссылка КАК Ссылка ИЗ Справочник.ПрофилиГруппДоступа КАК П ГДЕ П.Наименование = &Имя И НЕ П.ПометкаУдаления";
Запрос.УстановитьПараметр("Имя", {name});
Выб = Запрос.Выполнить().Выбрать();
Рез = "";
Если Выб.Следующий() Тогда
	Профиль = Выб.Ссылка;
	Для Каждого С Из Профиль.Роли Цикл
		Рез = Рез + Строка(С.Роль) + Символы.ПС;
	КонецЦикла;
КонецЕсли;
Результат = Рез;
"""

# Копирование профиля: читаем роли источника и записываем в приёмник.
# Композитные ссылки (ИОМ/ИОР) переносятся как есть — без повторного поиска
# по UUID, поэтому тип ссылки не теряется.
COPY_ROLES = """
Ист = Справочники.ПрофилиГруппДоступа.НайтиПоНаименованию({src}, Истина);
Приёмник = Справочники.ПрофилиГруппДоступа.НайтиПоНаименованию({dst}, Истина);
Если Ист = Неопределено Тогда
	Результат = "ERR|нет исходного профиля";
ИначеЕсли Приёмник = Неопределено Тогда
	Результат = "ERR|нет профиля-приёмника";
Иначе
	Приёмник.Роли.Очистить();
	Для Каждого С Из Ист.Роли Цикл
		Нов = Приёмник.Роли.Добавить();
		Нов.Роль = С.Роль;
	КонецЦикла;
	Приёмник.Комментарий = {comment};
	Попытка
		Приёмник.Записать();
		Результат = "OK|" + Строка(Приёмник.Роли.Количество());
	Исключение
		Результат = "ERR|" + ОписаниеОшибки();
	КонецПопытки;
КонецЕсли;
"""

CREATE_PROFILE = """
Приёмник = Справочники.ПрофилиГруппДоступа.СоздатьЭлемент();
Приёмник.Наименование = {name};
Приёмник.Комментарий = {comment};
Приёмник.ПоставляемыйПрофильИзменен = Ложь;
Ист = Справочники.ПрофилиГруппДоступа.НайтиПоНаименованию({src}, Истина);
Если Ист = Неопределено Тогда
	Результат = "ERR|нет исходного профиля";
Иначе
	Для Каждого С Из Ист.Роли Цикл
		Нов = Приёмник.Роли.Добавить();
		Нов.Роль = С.Роль;
	КонецЦикла;
	// Виды и значения доступа переносим 1:1 — они определяют ограничения RLS
	Для Каждого С Из Ист.ВидыДоступа Цикл
		Нов = Приёмник.ВидыДоступа.Добавить();
		Нов.ВидДоступа = С.ВидДоступа;
		Нов.ВсеРазрешены = С.ВсеРазрешены;
		Нов.Предустановленный = С.Предустановленный;
	КонецЦикла;
	Для Каждого С Из Ист.ЗначенияДоступа Цикл
		Нов = Приёмник.ЗначенияДоступа.Добавить();
		Нов.ВидДоступа = С.ВидДоступа;
		Нов.ЗначениеДоступа = С.ЗначениеДоступа;
		Нов.ВключаяНижестоящие = С.ВключаяНижестоящие;
	КонецЦикла;
	Для Каждого С Из Ист.Назначение Цикл
		Нов = Приёмник.Назначение.Добавить();
		Нов.ТипПользователей = С.ТипПользователей;
	КонецЦикла;
	Попытка
		Приёмник.Записать();
		Результат = "OK|" + Строка(Приёмник.Роли.Количество());
	Исключение
		Результат = "ERR|" + ОписаниеОшибки();
	КонецПопытки;
КонецЕсли;
"""


def main() -> int:
    setup_stdout()
    parser = argparse.ArgumentParser(description="Создание профиля копированием")
    add_common_args(parser)
    parser.add_argument("--name", required=True, help="Имя нового профиля")
    parser.add_argument("--from", dest="source", required=True, help="Профиль-образец")
    parser.add_argument(
        "--comment", default="", help="Комментарий нового профиля"
    )
    parser.add_argument(
        "--apply", action="store_true", help="Записать в базу (без флага — только показать)"
    )
    args = parser.parse_args()

    client = Client(resolve_url(args.url))

    src_state = client.run(EXISTS.format(name=bsl_string(args.source)))
    if src_state.startswith("нет"):
        fail(f'профиль-образец «{args.source}» не найден')
    src_roles = int(src_state.split("|")[1])
    print(f"Профиль-образец «{args.source}»: ролей {src_roles}")

    dst_state = client.run(EXISTS.format(name=bsl_string(args.name)))
    dst_exists = dst_state.startswith("да")
    if dst_exists:
        print(
            f"Профиль «{args.name}» уже существует (ролей "
            f"{dst_state.split('|')[1]}) — роли будут заменены."
        )
    else:
        print(f"Профиль «{args.name}» будет создан.")

    print()
    print("Что будет скопировано:")
    print("  - состав ролей")
    print("  - виды доступа (ограничения RLS)")
    print("  - значения доступа")
    print("  - назначение (типы пользователей)")
    print()

    if not args.apply:
        print("Режим проверки: в базу ничего не записано.")
        print("Чтобы записать, повторите команду с флагом --apply.")
        return 0

    comment = bsl_string(args.comment)
    if dst_exists:
        code = COPY_ROLES.format(
            src=bsl_string(args.source), dst=bsl_string(args.name), comment=comment
        )
    else:
        code = CREATE_PROFILE.format(
            src=bsl_string(args.source),
            name=bsl_string(args.name),
            comment=comment,
        )

    result = client.run(code).strip()
    if result.startswith("ERR|"):
        fail(f"запись не выполнена: {result[4:]}")
    count = result.split("|")[1] if "|" in result else "?"
    print(f"Готово: профиль «{args.name}», ролей {count}")

    if args.json:
        print(
            json.dumps(
                {"name": args.name, "source": args.source, "roles": count},
                ensure_ascii=False,
                indent=2,
            )
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
